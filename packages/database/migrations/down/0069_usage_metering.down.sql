-- ما الذي يُفقد: عدّادات الاستخدام (استدعاءات الـAPI اليومية وإرسالات البريد الشهرية).
-- وهي **قياس** لا مستند: لا فاتورة ولا قيد يقرأها، وحذفها لا يُلغي شيئاً وقع — لكنه يعني أن
-- الاستخدام يُعاد عدّه من الصفر بعد إعادة الترحيل، وهذا مقبول لأنه لا يوجد تراكم تاريخي
-- يُبنى عليه بعد (لوحات الإيراد تقرأ التراخيص، لا العدّادات).
--
-- ما الذي يبقى: كل جداول الحقيقة التي تُقاس منها المقاييس الستة
-- (`memberships` · `branches` · `items` · `sales_invoices` · `whatsapp_messages` · `files`)
-- وحدود المنصة في `platform_settings` (`limits.*`) — فالتراجع يوقف **القياس والتطبيق** ولا
-- يمسّ بيانات العميل. بعد التراجع تفشل `/usage` في اللوحة و`/settings/usage` في سطح العميل
-- (لا جدول يقيس منه)، ويُرفض كل مقياسٍ له حدٌّ مطبَّق؟ لا: اعتراض الرفض يقرأ العدّاد، فبلا
-- جدولٍ لا يمنع الاستدعاءات — وهذا هو الفرق الوحيد المرئي للمستخدم بعد التراجع.

DROP TABLE IF EXISTS usage_counters;

-- وسياسة الطائرة الإدارية التي أضافها الترحيل على `items` و`files` و`whatsapp_messages`:
-- تُسحب كما أُضيفت، فتبقى سياسة العزل وحدها (وهو ما كان قبل P-C5).
DO $$
DECLARE
  t text;
BEGIN
  FOREACH t IN ARRAY ARRAY['items', 'files', 'whatsapp_messages'] LOOP
    EXECUTE format('DROP POLICY IF EXISTS platform_admin_plane ON %I', t);
  END LOOP;
END $$;
